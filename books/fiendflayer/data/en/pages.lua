    summary = "A fiend with mind flayer traits, not a mind flayer.",
    body = [==[
**FiendFlayer**, written as one word. The names *soulflayer* and *hellflayer* were dropped because they already have many pop-culture references.

The reference point is the variants in which the illithids transformed dragons and beholders: the creature gains an illithid layer without losing its original essence.

Here the infernal nature replaces the illithid nature. Instead of becoming an ordinary mind flayer, he becomes a fiend with mind flayer traits. The transformation is not a ceremorphosis: it is a new transformation, of a fiend into this new creature.

## An accident
The character is the result of an accident. Once the infernal nature is 100% overcome through this accident, the illithids will be able to assimilate any fiend. That is why the name is broad.

## A new faction
The FiendFlayer can persuade other devils to follow him, creating a new faction within the Hells, since he too was one of the oppressed.

::: lore
Official illithid variants: the mindwitness (beholder), the brainstealer dragon and the elder brain dragon, the urophion (roper) and the mozgriken (deep gnome, sustained by a negative energy ritual).

With a beholder, the fusion does not happen through a tadpole: it is taken to an elder brain's brine pool and becomes a mindwitness. The brainstealer dragon is the result of ceremorphosis; the elder brain dragon appears when an elder brain attaches itself to a dragon, which is not ceremorphosis.
:::
