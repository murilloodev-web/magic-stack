## What the parasite does to the soul
In normal ceremorphosis, the parasite takes over the body, but in the long run it also affects the person's soul, changing their personality, even outside the hivemind. It does not show on the outside, but the host is affected inside, little by little.

In his case, the years of the parasite affecting the child's "soul" affected the devil's own essence.

::: lore
In 5e, a full ceremorphosis takes about a week. In non-humanoids it usually fails and kills both host and larva. It has happened that a ceremorphosis stopped halfway, leaving a human body with an illithid's brain, personality and digestive tract.
