-- tools/cover.lua — writes cover.html, the book's cover on the Magic Stack
-- table (150×200 px): the title in gold on ruby leather, a framed pixel
-- portrait of the FiendFlayer over Avernus, and purple creeping in from
-- the corners. Run it from the book folder after changing tools/art.lua:
--
--   lua tools/cover.lua > cover.html
--
-- {{TITLE}}, {{SYSTEM}} and {{AUTHOR}} are filled in by the root build.lua
-- in each language. The shelf page loads Silkscreen and Pirata One.

local art = dofile("tools/art.lua")
local W, H = 112, 84
local portrait = art.svg(art.scene(W, H, { cx = 56, top = 12, flat = true }), ' style="display:block"')

-- purple spots spreading in from the corners, like the skin on the concept sheet
local spots = { ["#5f2493"] = {}, ["#8a3fc4"] = {} }
for y = 0, 199, 3 do
  for x = 0, 149, 3 do
    local dx, dy = math.min(x, 149 - x) / 75, math.min(y, 199 - y) / 100
    local edge = 1 - math.min(dx, dy) * 1.0
    if art.noise(x, y, 21) < (edge - .82) * 4 then
      local list = spots[art.noise(x, y, 22) < .5 and "#5f2493" or "#8a3fc4"]
      list[#list + 1] = string.format("M%d %dh3v3h-3z", x, y)
    end
  end
end

local out = {}
local function add(s) out[#out + 1] = s end
add("<!-- Cover of FiendFlayer on the Magic Stack table (150×200 px).")
add("     Generated by tools/cover.lua from tools/art.lua; do not edit by hand.")
add("     {{TITLE}}, {{SYSTEM}} and {{AUTHOR}} are filled by the build, in each language. -->")
add('<div style="position:absolute; inset:0; overflow:hidden; background:#6e1420; background-image:radial-gradient(ellipse 90% 70% at 50% 45%, #9a2230 0%, transparent 70%), repeating-linear-gradient(0deg, rgb(0 0 0 / .08) 0 1px, transparent 1px 4px);">')
add('  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 150 200" width="150" height="200" shape-rendering="crispEdges" style="position:absolute; inset:0; display:block">'
  .. '<path fill="#5f2493" d="' .. table.concat(spots["#5f2493"]) .. '"/><path fill="#8a3fc4" d="' .. table.concat(spots["#8a3fc4"]) .. '"/></svg>')
add("  <div style=\"position:absolute; left:8px; right:8px; top:12px; text-align:center; font-family:'Pirata One', serif; font-size:27px; line-height:.86; color:#f2c46a; text-shadow:2px 2px 0 #12070b, 0 0 10px rgb(167 92 232 / .6);\">{{TITLE}}</div>")
add(string.format('  <div style="position:absolute; left:%dpx; top:68px; box-shadow:0 0 0 2px #12070b, 0 0 0 4px #c9a24a, 0 0 0 6px #12070b, 0 0 14px 6px rgb(167 92 232 / .35);">%s</div>', (150 - W) // 2, portrait))
add("  <div style=\"position:absolute; left:8px; right:8px; top:166px; text-align:center; font-family:'Silkscreen', monospace; font-size:7px; color:#f2c46a; letter-spacing:.06em;\">{{SYSTEM}} · AVERNUS</div>")
add("  <div style=\"position:absolute; left:8px; right:8px; bottom:9px; text-align:center; font-family:'Silkscreen', monospace; font-size:7px; line-height:1.3; color:#f1e3d3;\">{{AUTHOR}}</div>")
add('  <span style="position:absolute; inset:0; box-shadow:inset 0 0 0 2px #12070b, inset 0 0 0 4px #8a3fc4;"></span>')
add("</div>")
print(table.concat(out, "\n"))
